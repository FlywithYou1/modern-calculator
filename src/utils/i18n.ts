type TranslationKey = keyof typeof TRANSLATIONS['zh-CN']

let currentLanguage: LanguageCode = 'zh-CN'
const listeners = new Set<(language: LanguageCode) => void>()

function format(template: string, replacements?: ReplacementMap): string {
  if (!replacements) return template
  return template.replace(/{{(\w+)}}/g, (_, token: string) => {
    const value = replacements[token]
    return value !== undefined ? String(value) : ''
  })
}

export function translate(key: TranslationKey | string, replacements?: ReplacementMap): string {
  const table = TRANSLATIONS[currentLanguage]
  const fallback = TRANSLATIONS['en-US']
  const value = table[key as TranslationKey] ?? fallback[key as TranslationKey] ?? key
  return format(value, replacements)
}

export function setLanguage(language: LanguageCode): void {
  if (!(language in TRANSLATIONS)) return
  if (currentLanguage === language) return
  currentLanguage = language
  listeners.forEach(listener => listener(language))
}

export function getCurrentLanguage(): LanguageCode {
  return currentLanguage
}

export function onLanguageChange(listener: (language: LanguageCode) => void): () => void {
  listeners.add(listener)
  return () => {
    listeners.delete(listener)
  }
}

export function getAvailableLanguages(): Array<{ code: LanguageCode; label: string }> {
  return (Object.keys(TRANSLATIONS) as LanguageCode[]).map(code => ({
    code,
    label: TRANSLATIONS[currentLanguage][`language.name.${code}` as TranslationKey] ??
      TRANSLATIONS['en-US'][`language.name.${code}` as TranslationKey] ?? code,
  }))
}

const ATTRIBUTE_BINDINGS: Array<{
  dataKey: keyof DOMStringMap
  selector: string
  apply: (el: HTMLElement, value: string) => void
}> = [
  {
    dataKey: 'i18nTitle',
    selector: '[data-i18n-title]',
    apply: (el, value) => el.setAttribute('title', value),
  },
  {
    dataKey: 'i18nAriaLabel',
    selector: '[data-i18n-aria-label]',
    apply: (el, value) => el.setAttribute('aria-label', value),
  },
  {
    dataKey: 'i18nAriaDescription',
    selector: '[data-i18n-aria-description]',
    apply: (el, value) => el.setAttribute('aria-description', value),
  },
  {
    dataKey: 'i18nPlaceholder',
    selector: '[data-i18n-placeholder]',
    apply: (el, value) => el.setAttribute('placeholder', value),
  },
]

export function applyTranslations(root: ParentNode): void {
  const elements = root.querySelectorAll<HTMLElement>('[data-i18n]')
  elements.forEach(el => {
    const key = el.dataset.i18n
    if (key) {
      el.textContent = translate(key)
    }
  })

  ATTRIBUTE_BINDINGS.forEach(binding => {
    const attrElements = root.querySelectorAll<HTMLElement>(binding.selector)
    attrElements.forEach(el => {
      const key = el.dataset[binding.dataKey]
      if (key) {
        binding.apply(el, translate(key))
      }
    })
  })
}

